import { spawnSync } from 'node:child_process';
import { readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { verify } from '../src/index.mjs';
const cwd = fileURLToPath(new URL('.', import.meta.url));
const build = spawnSync(process.execPath, ['node_modules/@angular/cli/bin/ng.js', 'build', 'smoke'], { cwd, stdio: 'inherit', env: { ...process.env, NG_CLI_ANALYTICS: 'false' } });
if (build.status !== 0) throw new Error(`Official Angular build failed: ${build.status}`);
const dist = fileURLToPath(new URL('dist/browser/', import.meta.url));
const contract = JSON.parse(await readFile(new URL('contract.json', import.meta.url), 'utf8'));
const positive = await verify(dist, contract);
await mkdir(new URL('reports/', import.meta.url), { recursive: true });
await writeFile(new URL('reports/positive.json', import.meta.url), JSON.stringify(positive, null, 2) + '\n');
assert.equal(positive.status, 'pass');
await rm(new URL('dist/browser/main.js', import.meta.url));
const negative = await verify(dist, contract);
await writeFile(new URL('reports/missing-bundle.json', import.meta.url), JSON.stringify(negative, null, 2) + '\n');
assert.equal(negative.status, 'fail');
console.log('Official Angular build: positive pass; removed bundle: fail. No browser/runtime assertion.');
